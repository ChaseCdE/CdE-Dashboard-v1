from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Optional, Union

import pandas as pd

CONTRACT_VERSION = "1.2"
ROOT = Path(__file__).resolve().parent.parent.parent
PROCESSED_DIR = ROOT / "data" / "processed"
SITE_DATA_DIR = ROOT / "site" / "data"

UNITS = {"pct", "pct_change", "pp", "index", "points", "currency", "rate", "persons", "hours", "years", "count"}
FREQUENCIES = {"D", "W", "M", "Q", "A", "X"}
X_TYPES = {"date", "number", "category"}
SOURCES = {
    "ine": "INE",
    "eurostat": "Eurostat",
    "bde": "Banco de España",
    "yahoo": "Yahoo Finance",
    "mivau": "Ministerio de Vivienda y Agenda Urbana",
    "registradores": "Colegio de Registradores",
}
MAX_DECIMALS = 4


@dataclass
class Field:
    """One value column per row. `column` is the column in the processed CSV."""

    key: str
    label_es: str
    unit: str
    decimals: int
    column: Optional[str] = None  # default: same as key
    currency: Optional[str] = None
    scale: int = 0
    note_es: Optional[str] = None

    def to_json(self) -> dict:
        out = {"key": self.key, "label_es": self.label_es, "unit": self.unit, "decimals": self.decimals}
        if self.currency:
            out["currency"] = self.currency
        if self.scale:
            out["scale"] = self.scale
        if self.note_es:
            out["note_es"] = self.note_es
        return out


@dataclass
class Series:
    """
    One line/bar group in the file.

    - `where`: optional {column: value} filter applied to the CSV before
      extracting this series (long-format files).
    - `columns`: optional {field_key: csv_column} override for this series
      (wide-format files such as Spain vs EU27 comparisons).
    """

    key: str
    label_es: str
    where: dict = field(default_factory=dict)
    columns: dict = field(default_factory=dict)
    as_of_column: Optional[str] = None


SeriesSpec = Union[list, Callable[[pd.DataFrame], list]]


def long_series(category_column: str, label_column: Optional[str] = None,
                labels: Optional[dict] = None, order: Optional[list] = None) -> Callable[[pd.DataFrame], list]:
    """Build one Series per distinct value of `category_column` (long-format CSVs)."""

    def build(df: pd.DataFrame) -> list:
        keys = list(dict.fromkeys(df[category_column].dropna().astype(str)))
        if order:
            keys = [k for k in order if k in keys] + [k for k in keys if k not in order]
        out = []
        for k in keys:
            if labels and k in labels:
                label = labels[k]
            elif label_column:
                label = str(df.loc[df[category_column].astype(str) == k, label_column].iloc[0])
            else:
                label = k
            out.append(Series(key=slug(k), label_es=label, where={category_column: k}))
        return out

    return build


@dataclass
class Dataset:
    source: str  # key of SOURCES
    indicator: str
    csv: str  # path relative to data/processed/
    title_es: str
    source_dataset: str
    source_url: str
    frequency: str
    fields: list
    series: SeriesSpec
    description_es: Optional[str] = None
    x_column: str = "date"
    x_type: str = "date"
    start: Optional[str] = None  # drop rows before this date (date datasets only)
    # Contract v1.2: staleness allowance in days for sources with a known long publication
    # lag (e.g. annual R&D). None = the frequency default in the contract.
    stale_after_days: Optional[int] = None
    # Sources outside the official statistics APIs (e.g. a portal behind a web firewall). If
    # the processed CSV is missing (first run without a cached download), the exporter keeps
    # the previously published file instead of failing the whole export.
    optional: bool = False

    @property
    def id(self) -> str:
        return f"{self.source}.{self.indicator}"

    @property
    def path(self) -> str:
        return f"{self.source}/{self.indicator}.json"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def slug(s: str) -> str:
    import re
    import unicodedata

    s = unicodedata.normalize("NFKD", str(s)).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-zA-Z0-9]+", "_", s).strip("_").lower()
    return s or "x"


def _clean_number(v) -> Optional[float]:
    if v is None:
        return None
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    if math.isnan(f) or math.isinf(f):
        return None
    r = round(f, MAX_DECIMALS)
    return int(r) if r.is_integer() and abs(r) < 1e15 else r


def _format_x(series: pd.Series, x_type: str) -> pd.Series:
    if x_type == "date":
        parsed = pd.to_datetime(series, errors="coerce", utc=False)
        if getattr(parsed.dt, "tz", None) is not None:
            parsed = parsed.dt.tz_localize(None)
        return parsed.dt.strftime("%Y-%m-%d")
    if x_type == "number":
        return series.map(_clean_number)
    return series.astype(str)


