def build_dataset(ds: Dataset, generated_at: str) -> dict:
    csv_path = PROCESSED_DIR / ds.csv
    df = pd.read_csv(csv_path)

    if ds.x_type == "date" and ds.start:
        d = pd.to_datetime(df[ds.x_column], errors="coerce", utc=True).dt.tz_localize(None)
        df = df[d >= pd.Timestamp(ds.start)]

    series_list = ds.series(df) if callable(ds.series) else ds.series
    out_series = []
    for s in series_list:
        sub = df
        for col, val in s.where.items():
            sub = sub[sub[col].astype(str) == str(val)]
        x = _format_x(sub[ds.x_column], ds.x_type)
        cols = []
        for f in ds.fields:
            col = s.columns.get(f.key) or f.column or f.key
            if col not in sub.columns:
                raise KeyError(f"{ds.id}: column '{col}' (field '{f.key}', series '{s.key}') not in {ds.csv}")
            cols.append(sub[col].tolist())
        rows = []
        for i, xv in enumerate(x.tolist()):
            if xv is None or (isinstance(xv, float) and math.isnan(xv)) or xv == "NaT":
                continue
            vals = [_clean_number(c[i]) for c in cols]
            if all(v is None for v in vals):
                continue
            rows.append([xv, *vals])
        # Duplicate x within a series means a processor mixed two series: fail loudly
        # instead of silently keeping one (audit M6).
        dedup = {}
        for r in rows:
            if r[0] in dedup and dedup[r[0]][1:] != r[1:]:
                raise ValueError(f"{ds.id}: series '{s.key}' has conflicting rows for x={r[0]}: {dedup[r[0]]} vs {r}")
            dedup[r[0]] = r
        rows = [dedup[k] for k in sorted(dedup)] if ds.x_type != "category" else list(dedup.values())

        entry = {"key": s.key, "label_es": s.label_es, "data": rows}
        if s.as_of_column and s.as_of_column in sub.columns and len(sub):
            entry["as_of"] = _format_x(sub[s.as_of_column], "date").max()
        out_series.append(entry)

    last_obs = None
    if ds.x_type == "date":
        xs = [s["data"][-1][0] for s in out_series if s["data"]]
        last_obs = max(xs) if xs else None

    obj = {
        "contract_version": CONTRACT_VERSION,
        "id": ds.id,
        "title_es": ds.title_es,
    }
    if ds.description_es:
        obj["description_es"] = ds.description_es
    obj.update({
        "source": {"name": SOURCES[ds.source], "dataset": ds.source_dataset, "url": ds.source_url},
        "frequency": ds.frequency,
        "x": {"key": ds.x_column if ds.x_type != "date" else "date", "type": ds.x_type},
        "fields": [f.to_json() for f in ds.fields],
        "series": out_series,
        "last_observation": last_obs,
        "generated_at": generated_at,
    })
    if ds.stale_after_days is not None:
        obj["stale_after_days"] = int(ds.stale_after_days)
    return obj


def latest_values(obj: dict) -> list:
    keys = [f["key"] for f in obj["fields"]]
    out = []
    for s in obj["series"]:
        latest = {}
        for i, k in enumerate(keys, start=1):
            latest[k] = None
            for row in reversed(s["data"]):
                if row[i] is not None:
                    latest[k] = [row[0], row[i]]
                    break
        out.append({"key": s["key"], "label_es": s["label_es"], "latest": latest})
    return out


def manifest_entry(ds: Dataset, obj: dict) -> dict:
    return {
        "id": obj["id"],
        "path": ds.path,
        "title_es": obj["title_es"],
        "source": obj["source"]["name"],
        "frequency": obj["frequency"],
        "last_observation": obj["last_observation"],
        "fields": [f["key"] for f in obj["fields"]],
        "series": latest_values(obj),
    }


def now_utc() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
